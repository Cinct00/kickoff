"""Shared helpers: repo discovery, file listing, language detection, token estimates."""
from __future__ import annotations

import hashlib
import os
import re
import stat
import subprocess
import sys
from pathlib import Path

LANG_BY_EXT = {
    ".py": "python", ".pyi": "python",
    ".js": "javascript", ".jsx": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".ts": "typescript", ".tsx": "typescript", ".mts": "typescript", ".cts": "typescript",
    ".go": "go",
    ".java": "java", ".kt": "kotlin", ".kts": "kotlin", ".scala": "scala",
    ".cs": "csharp",
    ".rs": "rust",
    ".c": "c", ".h": "c", ".cc": "cpp", ".cpp": "cpp", ".cxx": "cpp", ".hpp": "cpp", ".hh": "cpp", ".hxx": "cpp",
    ".php": "php", ".rb": "ruby", ".swift": "swift",
    ".md": "markdown", ".mdx": "markdown",
}
CODE_LANGS = {l for l in LANG_BY_EXT.values() if l != "markdown"}

# Paths that are generated, vendored or otherwise noise for navigation.
SKIP_DIR_PARTS = {
    "node_modules", ".git", ".hg", ".svn", "vendor", "dist", "build", "out", "target", "bin", "obj",
    "__pycache__", ".venv", "venv", ".tox", ".mypy_cache", ".pytest_cache", ".next", ".nuxt",
    "coverage", ".gradle", ".idea", ".vscode", "Pods", "DerivedData", ".terraform", "site-packages",
}
SKIP_SUFFIXES = (
    ".min.js", ".min.css", ".map", ".lock", "-lock.json", ".lock.json", ".pb.go", "_pb2.py", ".g.cs",
    ".designer.cs", ".generated.ts", ".d.ts.map",
)
BINARY_EXTS = {
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".svg", ".pdf", ".zip", ".gz", ".tgz", ".bz2", ".xz",
    ".7z", ".jar", ".war", ".class", ".so", ".dll", ".dylib", ".exe", ".o", ".a", ".pyc", ".woff", ".woff2",
    ".ttf", ".otf", ".eot", ".mp3", ".mp4", ".mov", ".avi", ".wav", ".db", ".sqlite", ".bin", ".pkl", ".npy",
    ".parquet", ".onnx", ".pt", ".h5", ".psd", ".sketch", ".fig",
}
MAX_FILE_BYTES = int(os.environ.get("CODEMAP_MAX_FILE_BYTES", 1_000_000))

TEST_RE = re.compile(
    r"(^|/)([Tt]ests?|__tests__|[Ss]pecs?|[Tt]esting|UnitTests|IntegrationTests)/|(^|/)[^/]*[._-][Tt]ests?/|(^|/)[^/]*[a-z]Tests/"
    r"|(^|/)test_[^/]+\.py$|_test\.(py|go)$|\.(test|spec)\.[jt]sx?$"
    r"|(Test|Tests|Spec|IT)\.(java|kt|cs|scala)$|_spec\.rb$|Tests?\.swift$",
)


def est_tokens(text_or_len) -> int:
    """Rough token estimate (~4 chars per token for code and English)."""
    n = text_or_len if isinstance(text_or_len, int) else len(text_or_len)
    return (n + 3) // 4


def fmt_tokens(n: int) -> str:
    return f"{n / 1000:.1f}k" if n >= 1000 else str(n)


GENERATED_PATH_RE = re.compile(r"(^|/)(generated|Generated|gen)/|\.(generated|Generated|g|designer|Designer|g\.i)\.[a-z]+$|"
                               r"_pb2\.py$|\.pb\.go$|_generated\.(go|rs|py)$")
GENERATED_HEAD_RE = re.compile(r"<auto-generated|@generated|Code generated .* DO NOT EDIT|This file was automatically generated|"
                               r"DO NOT EDIT[.!]|automatically generated by", re.I)


def is_generated(path: str, text: str | None = None) -> bool:
    """Generated code: a conventional path, or a marker comment in the first lines of the file."""
    if GENERATED_PATH_RE.search(path):
        return True
    return bool(text) and bool(GENERATED_HEAD_RE.search(text[:600]))


def is_test_path(path: str) -> bool:
    return bool(TEST_RE.search(path))


def lang_of(path: str) -> str | None:
    p = path.lower()
    for ext, lang in LANG_BY_EXT.items():
        if p.endswith(ext):
            return lang
    return None


def git(args: list[str], cwd: Path) -> str | None:
    try:
        proc = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, timeout=60)
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return None
    return proc.stdout if proc.returncode == 0 else None


def find_repo_root(start: Path) -> Path:
    out = git(["rev-parse", "--show-toplevel"], start)
    if out and out.strip():
        return Path(out.strip()).resolve()
    return start.resolve()


def cache_dir() -> Path:
    if os.environ.get("CODEMAP_CACHE"):
        base = Path(os.environ["CODEMAP_CACHE"])
    elif sys.platform == "win32":
        base = Path(os.environ.get("LOCALAPPDATA", Path.home() / "AppData" / "Local")) / "ai-toolkit" / "codemap"
    else:
        base = Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache")) / "ai-toolkit" / "codemap"
    base.mkdir(parents=True, exist_ok=True)
    return base


def default_db_path(root: Path) -> Path:
    if os.environ.get("CODEMAP_DB"):
        return Path(os.environ["CODEMAP_DB"])
    slug = re.sub(r"[^A-Za-z0-9_.-]+", "-", root.name)[:40] or "repo"
    digest = hashlib.sha1(str(root).encode()).hexdigest()[:10]
    return cache_dir() / f"{slug}-{digest}.db"


def _skip(path: str) -> bool:
    parts = path.split("/")
    if any(p in SKIP_DIR_PARTS for p in parts[:-1]):
        return True
    low = path.lower()
    if low.endswith(SKIP_SUFFIXES):
        return True
    dot = low.rfind(".")
    return dot != -1 and low[dot:] in BINARY_EXTS


def load_config(root: Path) -> dict:
    """Optional `.codemap.json` in the repo root, plus CODEMAP_INCLUDE / CODEMAP_EXCLUDE (comma-separated globs).

    {"include": ["src/Generated/**/*.cs"],   # gitignored or normally-skipped files to index anyway
     "exclude": ["**/*.Designer.cs"]}        # tracked files to leave out
    """
    cfg = {"include": [], "exclude": []}
    f = root / ".codemap.json"
    if f.is_file():
        try:
            import json
            data = json.loads(f.read_text(encoding="utf-8"))
            for k in cfg:
                cfg[k] += [str(x) for x in data.get(k, []) if isinstance(x, str)]
        except (ValueError, OSError):
            pass
    for k, env in (("include", "CODEMAP_INCLUDE"), ("exclude", "CODEMAP_EXCLUDE")):
        cfg[k] += [g.strip() for g in os.environ.get(env, "").split(",") if g.strip()]
    return cfg


_GLOB_CACHE: dict = {}


def _glob_rx(g: str):
    """gitignore-style glob: `**/` = zero or more directories, `*` and `?` stay within one path segment."""
    rx = _GLOB_CACHE.get(g)
    if rx is None:
        out, i = [], 0
        while i < len(g):
            if g.startswith("**/", i):
                out.append("(?:.*/)?")
                i += 3
            elif g.startswith("**", i):
                out.append(".*")
                i += 2
            elif g[i] == "*":
                out.append("[^/]*")
                i += 1
            elif g[i] == "?":
                out.append("[^/]")
                i += 1
            else:
                out.append(re.escape(g[i]))
                i += 1
        rx = _GLOB_CACHE[g] = re.compile("".join(out) + "$")
    return rx


def _glob_match(path: str, globs) -> bool:
    return any(_glob_rx(g).match(path) for g in globs)


def included_ignored(root: Path, cfg: dict | None = None) -> list:
    """Gitignored (or normally-skipped) files that `.codemap.json` asks to index."""
    cfg = cfg or load_config(root)
    if not cfg["include"]:
        return []
    out = git(["ls-files", "-z", "--others", "--ignored", "--exclude-standard"], root) or ""
    tracked = git(["ls-files", "-z", "--cached"], root) or ""
    cands = [p for p in (out + "\0" + tracked).split("\0") if p]
    return sorted({p.replace("\\", "/") for p in cands if _glob_match(p, cfg["include"])
                   and not _glob_match(p, cfg["exclude"])})


def list_files(root: Path) -> list[str]:
    """Repo-relative POSIX paths of files worth indexing (respects .gitignore when in git, plus .codemap.json)."""
    cfg = load_config(root)
    out = git(["ls-files", "-z", "--cached", "--others", "--exclude-standard"], root)
    if out is not None:
        paths = [p for p in out.split("\0") if p]
    else:
        paths = []
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in SKIP_DIR_PARTS and not d.startswith(".")]
            rel = os.path.relpath(dirpath, root)
            for f in filenames:
                paths.append(f if rel == "." else f"{rel}/{f}".replace(os.sep, "/"))
    seen = set()
    result = []
    for p in paths:
        p = p.replace("\\", "/")
        if p in seen or _skip(p) or (cfg["exclude"] and _glob_match(p, cfg["exclude"])):
            continue
        seen.add(p)
        result.append(p)
    for p in included_ignored(root, cfg):  # explicit includes bypass .gitignore and the built-in skips
        if p not in seen:
            seen.add(p)
            result.append(p)
    return sorted(result)


def safe_path(root: Path, rel: str) -> Path | None:
    """root/rel if it is a regular file that stays inside root, else None.

    Repositories are untrusted: a committed symlink such as `config.py -> ~/.ssh/id_rsa` must not pull host
    files into the index or into an agent's context, and `x.js -> /dev/zero` must not be read at all.
    """
    if not rel or rel.startswith(("/", "\\")) or ".." in rel.replace("\\", "/").split("/"):
        return None
    p = root / rel
    try:
        if p.is_symlink():
            p.resolve().relative_to(root.resolve())
        if not stat.S_ISREG(p.stat().st_mode):
            return None
    except (OSError, ValueError, RuntimeError):
        return None
    return p


def read_text(path: Path) -> str | None:
    """Text of a regular file up to MAX_FILE_BYTES; None for binaries, oversized or unreadable files."""
    try:
        st = path.stat()
        if not stat.S_ISREG(st.st_mode) or st.st_size > MAX_FILE_BYTES:
            return None
        with path.open("rb") as fh:
            data = fh.read(MAX_FILE_BYTES + 1)
    except OSError:
        return None
    if len(data) > MAX_FILE_BYTES:
        return None
    if b"\0" in data[:8000]:
        return None
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return data.decode("latin-1")


def content_hash(text: str) -> str:
    return hashlib.sha1(text.encode("utf-8", "surrogatepass")).hexdigest()


def split_words(name: str) -> str:
    """'getUserById' / 'get_user_by_id' -> 'get user by id' (for search)."""
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", name)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1 \2", s)
    return re.sub(r"[_\-.:$]+", " ", s).lower().strip()
